ALTER TABLE operation_logs ALTER COLUMN ip TYPE VARCHAR(45) USING ip::text;

CREATE TABLE IF NOT EXISTS knowledge_base_members (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    knowledge_base_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    role VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_knowledge_base_members PRIMARY KEY (id),
    CONSTRAINT fk_kbm_knowledge_base FOREIGN KEY (knowledge_base_id)
        REFERENCES knowledge_bases (id) ON DELETE CASCADE,
    CONSTRAINT fk_kbm_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_kbm_knowledge_base_user UNIQUE (knowledge_base_id, user_id),
    CONSTRAINT ck_kbm_role CHECK (role IN ('EDITOR', 'VIEWER'))
);

CREATE INDEX IF NOT EXISTS idx_kbm_user
    ON knowledge_base_members (user_id);
CREATE INDEX IF NOT EXISTS idx_kbm_knowledge_base
    ON knowledge_base_members (knowledge_base_id);
CREATE INDEX IF NOT EXISTS idx_operation_logs_action_created_at
    ON operation_logs (action, created_at DESC);
