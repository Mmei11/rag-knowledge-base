-- Enable the vector type used by document_chunks.embedding.
CREATE EXTENSION IF NOT EXISTS vector;

-- Platform users.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username VARCHAR(50) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    nickname VARCHAR(100),
    role VARCHAR(20) NOT NULL DEFAULT 'USER',
    status VARCHAR(20) NOT NULL DEFAULT 'ENABLED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN')),
    CONSTRAINT ck_users_status CHECK (status IN ('ENABLED', 'DISABLED'))
);

-- Knowledge bases created by users.
CREATE TABLE knowledge_bases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    document_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_knowledge_bases PRIMARY KEY (id),
    CONSTRAINT fk_knowledge_bases_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT uk_knowledge_bases_user_name UNIQUE (user_id, name),
    CONSTRAINT ck_knowledge_bases_document_count
        CHECK (document_count >= 0)
);

-- Files uploaded to a knowledge base.
CREATE TABLE documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    knowledge_base_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    file_type VARCHAR(50) NOT NULL,
    file_size BIGINT NOT NULL,
    file_path VARCHAR(500) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_documents PRIMARY KEY (id),
    CONSTRAINT fk_documents_knowledge_base
        FOREIGN KEY (knowledge_base_id)
        REFERENCES knowledge_bases (id) ON DELETE CASCADE,
    CONSTRAINT fk_documents_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_documents_file_size CHECK (file_size >= 0),
    CONSTRAINT ck_documents_status
        CHECK (status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED'))
);

CREATE INDEX idx_documents_knowledge_base_id
    ON documents (knowledge_base_id);

CREATE INDEX idx_documents_user_id
    ON documents (user_id);

CREATE INDEX idx_documents_status_created_at
    ON documents (status, created_at);

-- Searchable text chunks extracted from documents.
CREATE TABLE document_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    document_id BIGINT NOT NULL,
    knowledge_base_id BIGINT NOT NULL,
    chunk_index INTEGER NOT NULL,
    content TEXT NOT NULL,
    token_count INTEGER NOT NULL DEFAULT 0,
    page_number INTEGER,
    embedding VECTOR(1024),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_document_chunks PRIMARY KEY (id),
    CONSTRAINT fk_document_chunks_document
        FOREIGN KEY (document_id) REFERENCES documents (id) ON DELETE CASCADE,
    CONSTRAINT fk_document_chunks_knowledge_base
        FOREIGN KEY (knowledge_base_id)
        REFERENCES knowledge_bases (id) ON DELETE CASCADE,
    CONSTRAINT uk_document_chunks_document_index
        UNIQUE (document_id, chunk_index),
    CONSTRAINT ck_document_chunks_chunk_index CHECK (chunk_index >= 0),
    CONSTRAINT ck_document_chunks_token_count CHECK (token_count >= 0),
    CONSTRAINT ck_document_chunks_page_number
        CHECK (page_number IS NULL OR page_number > 0),
    CONSTRAINT ck_document_chunks_content
        CHECK (LENGTH(BTRIM(content)) > 0)
);

CREATE INDEX idx_document_chunks_knowledge_base_id
    ON document_chunks (knowledge_base_id);

-- User conversations scoped to one knowledge base.
CREATE TABLE chat_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    knowledge_base_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_chat_sessions PRIMARY KEY (id),
    CONSTRAINT fk_chat_sessions_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_chat_sessions_knowledge_base
        FOREIGN KEY (knowledge_base_id)
        REFERENCES knowledge_bases (id) ON DELETE CASCADE,
    CONSTRAINT ck_chat_sessions_title
        CHECK (LENGTH(BTRIM(title)) > 0)
);

CREATE INDEX idx_chat_sessions_user_updated_at
    ON chat_sessions (user_id, updated_at DESC);

CREATE INDEX idx_chat_sessions_knowledge_base_id
    ON chat_sessions (knowledge_base_id);

-- User and assistant messages within a chat session.
CREATE TABLE chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    session_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    role VARCHAR(20) NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_chat_messages PRIMARY KEY (id),
    CONSTRAINT fk_chat_messages_session
        FOREIGN KEY (session_id)
        REFERENCES chat_sessions (id) ON DELETE CASCADE,
    CONSTRAINT fk_chat_messages_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_chat_messages_role
        CHECK (role IN ('USER', 'ASSISTANT')),
    CONSTRAINT ck_chat_messages_content
        CHECK (LENGTH(BTRIM(content)) > 0)
);

CREATE INDEX idx_chat_messages_session_created_at
    ON chat_messages (session_id, created_at, id);

CREATE INDEX idx_chat_messages_user_id
    ON chat_messages (user_id);

-- Document chunks cited by an assistant message.
CREATE TABLE message_references (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    message_id BIGINT NOT NULL,
    document_id BIGINT NOT NULL,
    chunk_id BIGINT NOT NULL,
    similarity DOUBLE PRECISION NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_message_references PRIMARY KEY (id),
    CONSTRAINT fk_message_references_message
        FOREIGN KEY (message_id)
        REFERENCES chat_messages (id) ON DELETE CASCADE,
    CONSTRAINT fk_message_references_document
        FOREIGN KEY (document_id) REFERENCES documents (id) ON DELETE CASCADE,
    CONSTRAINT fk_message_references_chunk
        FOREIGN KEY (chunk_id)
        REFERENCES document_chunks (id) ON DELETE CASCADE,
    CONSTRAINT uk_message_references_message_chunk
        UNIQUE (message_id, chunk_id),
    CONSTRAINT ck_message_references_similarity
        CHECK (similarity >= -1.0 AND similarity <= 1.0)
);

CREATE INDEX idx_message_references_document_id
    ON message_references (document_id);

CREATE INDEX idx_message_references_chunk_id
    ON message_references (chunk_id);

-- Audit records for important user and system operations.
CREATE TABLE operation_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT,
    action VARCHAR(100) NOT NULL,
    resource_type VARCHAR(50),
    resource_id BIGINT,
    ip INET,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_operation_logs PRIMARY KEY (id),
    CONSTRAINT fk_operation_logs_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_operation_logs_action
        CHECK (LENGTH(BTRIM(action)) > 0),
    CONSTRAINT ck_operation_logs_resource
        CHECK (
            (resource_type IS NULL AND resource_id IS NULL)
            OR
            (resource_type IS NOT NULL AND resource_id IS NOT NULL)
        )
);

CREATE INDEX idx_operation_logs_user_created_at
    ON operation_logs (user_id, created_at DESC);

CREATE INDEX idx_operation_logs_resource
    ON operation_logs (resource_type, resource_id);

CREATE INDEX idx_operation_logs_created_at
    ON operation_logs (created_at DESC);
